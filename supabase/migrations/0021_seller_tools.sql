DO $$
BEGIN
  IF to_regclass('public.smart_responses') IS NOT NULL AND NOT (
    SELECT count(DISTINCT column_name) = 5
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name = 'smart_responses'
      AND column_name IN ('id', 'user_id', 'title', 'content', 'sort_order')
  ) THEN
    IF to_regclass('public.smart_responses_legacy') IS NOT NULL THEN
      RAISE EXCEPTION 'Cannot preserve incompatible smart_responses: public.smart_responses_legacy already exists';
    END IF;
    ALTER TABLE public.smart_responses RENAME TO smart_responses_legacy;
  END IF;

  IF to_regclass('public.chat_thread_tags') IS NOT NULL AND NOT (
    SELECT count(DISTINCT column_name) = 4
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name = 'chat_thread_tags'
      AND column_name IN ('thread_id', 'user_id', 'tag_key', 'created_at')
  ) THEN
    IF to_regclass('public.chat_thread_tags_legacy') IS NOT NULL THEN
      RAISE EXCEPTION 'Cannot preserve incompatible chat_thread_tags: public.chat_thread_tags_legacy already exists';
    END IF;
    ALTER TABLE public.chat_thread_tags RENAME TO chat_thread_tags_legacy;
  END IF;
END;
$$;

