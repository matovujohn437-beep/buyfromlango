CREATE OR REPLACE FUNCTION public.set_listing_tags(
  p_listing_id bigint,
  p_tag_keys text[]
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  current_user_id uuid := auth.uid();
BEGIN
  IF current_user_id IS NULL OR NOT EXISTS (
    SELECT 1
    FROM public.listings
    WHERE id = p_listing_id
      AND user_id = current_user_id
  ) THEN
    RAISE EXCEPTION 'Listing not found or not owned by current user'
      USING ERRCODE = '42501';
  END IF;

  DELETE FROM public.listing_tags
  WHERE listing_id = p_listing_id AND user_id = current_user_id;

  INSERT INTO public.listing_tags (listing_id, user_id, tag_key)
  SELECT p_listing_id, current_user_id, tag_key
  FROM (
    SELECT DISTINCT unnest(COALESCE(p_tag_keys, ARRAY[]::text[])) AS tag_key
  ) AS selected
  WHERE tag_key IN (
    'maize_bulk_buyer',
    'coffee_retailer',
    'repeat_buyer',
    'follow_up',
    'priority',
    'new_contact'
  );

  IF EXISTS (
    SELECT 1
    FROM unnest(COALESCE(p_tag_keys, ARRAY[]::text[])) AS requested(tag_key)
    WHERE requested.tag_key NOT IN (
      'maize_bulk_buyer',
      'coffee_retailer',
      'repeat_buyer',
      'follow_up',
      'priority',
      'new_contact'
    )
  ) THEN
    RAISE EXCEPTION 'Unsupported tag'
      USING ERRCODE = '22023';
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.set_chat_thread_tags(
  p_thread_id bigint,
  p_tag_keys text[]
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  current_user_id uuid := auth.uid();
BEGIN
  IF current_user_id IS NULL OR NOT EXISTS (
    SELECT 1
    FROM public.chat_threads
    WHERE id = p_thread_id
      AND current_user_id IN (buyer_id, seller_id)
  ) THEN
    RAISE EXCEPTION 'Conversation not found or inaccessible'
      USING ERRCODE = '42501';
  END IF;

  DELETE FROM public.chat_thread_tags
  WHERE thread_id = p_thread_id AND user_id = current_user_id;

  INSERT INTO public.chat_thread_tags (thread_id, user_id, tag_key)
  SELECT p_thread_id, current_user_id, tag_key
  FROM (
    SELECT DISTINCT unnest(COALESCE(p_tag_keys, ARRAY[]::text[])) AS tag_key
  ) AS selected
  WHERE tag_key IN (
    'maize_bulk_buyer',
    'coffee_retailer',
    'repeat_buyer',
    'follow_up',
    'priority',
    'new_contact'
  );

  IF EXISTS (
    SELECT 1
    FROM unnest(COALESCE(p_tag_keys, ARRAY[]::text[])) AS requested(tag_key)
    WHERE requested.tag_key NOT IN (
      'maize_bulk_buyer',
      'coffee_retailer',
      'repeat_buyer',
      'follow_up',
      'priority',
      'new_contact'
    )
  ) THEN
    RAISE EXCEPTION 'Unsupported tag'
      USING ERRCODE = '22023';
  END IF;
END;
$$;

