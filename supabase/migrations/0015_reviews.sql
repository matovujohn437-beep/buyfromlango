create or replace view public.public_profiles as
select
  id,
  case when is_anonymous then null else full_name end as full_name,
  avatar_url,
  bio,
  district_id,
  subcounty_id,
  parish_id,
  is_anonymous,
  is_verified,
  created_at,
  role,
  account_type
from public.profiles;

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  reviewer_id uuid not null references public.profiles(id) on delete cascade,
  seller_id uuid not null references public.profiles(id) on delete cascade,
  rating smallint not null check (rating between 1 and 5),
  comment text check (comment is null or char_length(comment) <= 500),
  created_at timestamptz not null default now(),
  constraint reviews_no_self_review check (reviewer_id <> seller_id),
  constraint reviews_one_per_reviewer unique (reviewer_id, seller_id)
);

alter table public.reviews enable row level security;

drop policy if exists "Reviews are publicly readable" on public.reviews;
create policy "Reviews are publicly readable"
  on public.reviews for select
  using (true);

drop policy if exists "Authenticated users can create their own reviews"
  on public.reviews;
create policy "Authenticated users can create their own reviews"
  on public.reviews for insert to authenticated
  with check (
    auth.uid() = reviewer_id
    and reviewer_id <> seller_id
  );
