  ADD COLUMN is_feature_phone boolean NOT NULL DEFAULT false;

ALTER TABLE public.messages
  ADD COLUMN is_sms boolean NOT NULL DEFAULT false;

CREATE OR REPLACE VIEW public.public_profiles AS
SELECT
  profile.id,
  CASE WHEN profile.is_anonymous THEN NULL ELSE profile.full_name END AS full_name,
  profile.avatar_url,
  profile.bio,
  profile.district_id,
  profile.subcounty_id,
  profile.parish_id,
  profile.is_anonymous,
  profile.is_verified,
  profile.created_at,
  profile.role,
  profile.account_type,
  EXISTS (
    SELECT 1
    FROM auth.users AS auth_user
    WHERE auth_user.id = profile.id
      AND NULLIF(BTRIM(auth_user.email), '') IS NOT NULL
  ) AS has_email
FROM public.profiles AS profile;

CREATE TABLE public.sms_queue (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  thread_id bigint NOT NULL REFERENCES public.chat_threads(id) ON DELETE CASCADE,
  message_id bigint NOT NULL UNIQUE REFERENCES public.messages(id) ON DELETE CASCADE,
  sender_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  recipient_phone text NOT NULL,
  message_body text NOT NULL,
  status text NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'processing', 'sent', 'failed')),
  attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  next_attempt_at timestamptz NOT NULL DEFAULT now(),
  claimed_at timestamptz,
  last_error text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX sms_queue_pending_idx
  ON public.sms_queue (next_attempt_at, created_at)
  WHERE status IN ('pending', 'failed');

