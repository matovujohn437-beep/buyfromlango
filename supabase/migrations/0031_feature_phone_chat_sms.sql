CREATE OR REPLACE FUNCTION public.is_user_feature_phone(p_phone_number text)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.chat_threads AS thread
    JOIN public.profiles AS profile
      ON profile.id = CASE
        WHEN thread.buyer_id = auth.uid() THEN thread.seller_id
        ELSE thread.buyer_id
      END
    WHERE auth.uid() IN (thread.buyer_id, thread.seller_id)
      AND profile.phone = p_phone_number
      AND profile.is_feature_phone
  );
$$;

REVOKE ALL ON FUNCTION public.is_user_feature_phone(text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.is_user_feature_phone(text) TO authenticated;

CREATE OR REPLACE FUNCTION public.is_chat_participant_feature_phone(
  p_thread_id bigint
)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT COALESCE((
    SELECT CASE
      WHEN thread.buyer_id = auth.uid() THEN seller.is_feature_phone
      ELSE buyer.is_feature_phone
    END
    FROM public.chat_threads AS thread
    JOIN public.profiles AS buyer ON buyer.id = thread.buyer_id
    JOIN public.profiles AS seller ON seller.id = thread.seller_id
    WHERE thread.id = p_thread_id
      AND auth.uid() IN (thread.buyer_id, thread.seller_id)
  ), false);
$$;

REVOKE ALL ON FUNCTION public.is_chat_participant_feature_phone(bigint)
  FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.is_chat_participant_feature_phone(bigint)
  TO authenticated;

CREATE OR REPLACE FUNCTION public.send_chat_text_message(
  p_thread_id bigint,
  p_content text,
  p_reply_to bigint DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  sender uuid := auth.uid();
  receiver uuid;
  receiver_phone text;
  receiver_is_feature_phone boolean;
  new_message_id bigint;
BEGIN
  IF sender IS NULL THEN
    RAISE EXCEPTION 'Sign in is required' USING ERRCODE = '42501';
  END IF;
  IF NULLIF(BTRIM(p_content), '') IS NULL OR length(p_content) > 4000 THEN
    RAISE EXCEPTION 'Message must contain 1 to 4000 characters'
      USING ERRCODE = '22023';
  END IF;

  SELECT CASE
      WHEN thread.buyer_id = sender THEN thread.seller_id
      ELSE thread.buyer_id
    END
  INTO receiver
  FROM public.chat_threads AS thread
  WHERE thread.id = p_thread_id
    AND sender IN (thread.buyer_id, thread.seller_id);
  IF NOT FOUND THEN
    RAISE EXCEPTION 'You are not a participant in this conversation'
      USING ERRCODE = '42501';
  END IF;

  IF p_reply_to IS NOT NULL AND NOT EXISTS (
    SELECT 1
    FROM public.messages AS reply
    WHERE reply.id = p_reply_to
      AND reply.thread_id = p_thread_id
  ) THEN
    RAISE EXCEPTION 'Reply target is not in this conversation'
      USING ERRCODE = '22023';
  END IF;

  SELECT profile.phone, profile.is_feature_phone
  INTO receiver_phone, receiver_is_feature_phone
  FROM public.profiles AS profile
  WHERE profile.id = receiver;

  IF receiver_is_feature_phone
     AND NULLIF(BTRIM(receiver_phone), '') IS NULL THEN
    RAISE EXCEPTION 'The recipient is marked as a feature-phone user but has no phone number'
      USING ERRCODE = '22023';
  END IF;

  INSERT INTO public.messages (
    thread_id,
    sender_id,
    content,
    media_type,
    reply_to,
    is_sms
  )
  VALUES (
    p_thread_id,
    sender,
    BTRIM(p_content),
    'text',
    p_reply_to,
    receiver_is_feature_phone
  )
  RETURNING id INTO new_message_id;

  IF receiver_is_feature_phone THEN
    INSERT INTO public.sms_queue (
      thread_id,
      message_id,
      sender_id,
      recipient_phone,
      message_body
    )
    VALUES (
      p_thread_id,
      new_message_id,
      sender,
      receiver_phone,
      pg_catalog.format(
        'Buy From Lango: %s. Reply using CHAT %s <your message>.',
        BTRIM(p_content),
        p_thread_id
      )
    );
  END IF;

  RETURN new_message_id;
END;
$$;

REVOKE ALL ON FUNCTION public.send_chat_text_message(bigint, text, bigint)
  FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.send_chat_text_message(bigint, text, bigint)
  TO authenticated;

CREATE OR REPLACE FUNCTION public.claim_chat_sms(p_batch_size integer DEFAULT 20)
RETURNS TABLE (
  queue_id bigint,
  recipient_phone text,
  message_body text
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  RETURN QUERY
  WITH candidates AS (
    SELECT queue.id
    FROM public.sms_queue AS queue
    WHERE queue.status IN ('pending', 'failed')
      AND queue.attempts < 5
      AND queue.next_attempt_at <= pg_catalog.now()
    ORDER BY queue.created_at
    LIMIT GREATEST(1, LEAST(COALESCE(p_batch_size, 20), 100))
    FOR UPDATE SKIP LOCKED
  )
  UPDATE public.sms_queue AS queue
  SET status = 'processing',
      attempts = queue.attempts + 1,
      claimed_at = pg_catalog.now(),
      last_error = NULL
  FROM candidates
  WHERE queue.id = candidates.id
  RETURNING queue.id, queue.recipient_phone, queue.message_body;
END;
$$;

CREATE OR REPLACE FUNCTION public.finish_chat_sms(
  p_queue_id bigint,
  p_success boolean,
  p_error text DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  UPDATE public.sms_queue
  SET status = CASE WHEN p_success THEN 'sent' ELSE 'failed' END,
      next_attempt_at = pg_catalog.now() + interval '5 minutes',
      claimed_at = NULL,
      last_error = CASE
        WHEN p_success THEN NULL
        ELSE pg_catalog.left(COALESCE(p_error, 'SMS delivery failed.'), 500)
      END
  WHERE id = p_queue_id
    AND status = 'processing';
  IF NOT FOUND THEN
    RAISE EXCEPTION 'SMS queue job was not found or was already completed';
  END IF;
END;
$$;

REVOKE ALL ON FUNCTION public.claim_chat_sms(integer) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.finish_chat_sms(bigint, boolean, text)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.claim_chat_sms(integer) TO service_role;
GRANT EXECUTE ON FUNCTION public.finish_chat_sms(bigint, boolean, text)
  TO service_role;
