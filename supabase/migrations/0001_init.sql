CREATE TABLE public.listings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  category_id text NOT NULL REFERENCES public.categories(id) ON DELETE RESTRICT,
  title text NOT NULL CHECK (length(btrim(title)) > 0),
  description text,
  price_ugx numeric(14, 2) CHECK (price_ugx IS NULL OR price_ugx >= 0),
  is_negotiable boolean NOT NULL DEFAULT true,
  quantity text,
  district_id integer REFERENCES public.districts(id) ON DELETE SET NULL,
  subcounty_id integer REFERENCES public.subcounties(id) ON DELETE SET NULL,
  parish_id integer REFERENCES public.parishes(id) ON DELETE SET NULL,
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'paused', 'sold', 'removed')),
  is_anonymous boolean NOT NULL DEFAULT false,
  is_featured boolean NOT NULL DEFAULT false,
  view_count integer NOT NULL DEFAULT 0 CHECK (view_count >= 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.listing_media (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  listing_id bigint NOT NULL REFERENCES public.listings(id) ON DELETE CASCADE,
  media_url text NOT NULL,
  media_type text NOT NULL DEFAULT 'image' CHECK (media_type IN ('image', 'video')),
  sort_order integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
