CREATE TABLE public.districts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE public.subcounties (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  district_id integer NOT NULL REFERENCES public.districts(id) ON DELETE CASCADE,
  name text NOT NULL,
  is_active boolean NOT NULL DEFAULT true,
  UNIQUE (district_id, name),
  UNIQUE (district_id, id)
);

CREATE TABLE public.parishes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subcounty_id integer NOT NULL REFERENCES public.subcounties(id) ON DELETE CASCADE,
  name text NOT NULL,
  is_active boolean NOT NULL DEFAULT true,
  UNIQUE (subcounty_id, name),
  UNIQUE (subcounty_id, id)
);

CREATE TABLE public.app_settings (
  key text PRIMARY KEY,
  value jsonb NOT NULL,
  description text,
  is_public boolean NOT NULL DEFAULT true,
  updated_at timestamptz NOT NULL DEFAULT now()
