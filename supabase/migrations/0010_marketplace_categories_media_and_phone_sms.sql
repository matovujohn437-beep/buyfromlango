CREATE OR REPLACE FUNCTION public.request_seller_phone_sms(p_order_id bigint)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  requesting_seller uuid := auth.uid();
  order_status text;
  existing_status text;
BEGIN
  IF requesting_seller IS NULL THEN
    RAISE EXCEPTION 'Sign in is required'
      USING ERRCODE = '42501';
  END IF;

  SELECT status INTO order_status
  FROM public.orders
  WHERE id = p_order_id
    AND seller_id = requesting_seller
  FOR UPDATE;

  IF NOT FOUND OR order_status <> 'accepted' THEN
    RAISE EXCEPTION 'Only the seller can share a number after accepting the offer'
      USING ERRCODE = '42501';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM public.profiles AS seller
    WHERE seller.id = requesting_seller
      AND seller.phone IS NOT NULL
      AND pg_catalog.length(pg_catalog.btrim(seller.phone)) > 0
  ) THEN
    RAISE EXCEPTION 'Add a phone number to your profile before sharing it'
      USING ERRCODE = '22023';
  END IF;

  INSERT INTO public.seller_phone_sms_queue (order_id)
  VALUES (p_order_id)
  ON CONFLICT (order_id) DO NOTHING;

  SELECT status INTO existing_status
  FROM public.seller_phone_sms_queue
  WHERE order_id = p_order_id;

  IF existing_status = 'sent' THEN
    RETURN 'sent';
  END IF;

  UPDATE public.seller_phone_sms_queue
  SET status = 'queued',
      attempts = 0,
      next_attempt_at = pg_catalog.now(),
      claimed_at = NULL,
      last_error = NULL
  WHERE order_id = p_order_id
    AND status = 'failed';

  RETURN 'queued';
END;
$$;

CREATE OR REPLACE FUNCTION public.claim_seller_phone_sms(p_batch_size integer DEFAULT 20)
RETURNS TABLE (queue_id bigint, order_id bigint, buyer_id uuid, seller_id uuid)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF COALESCE(auth.role(), '') <> 'service_role' THEN
    RAISE EXCEPTION 'Service role is required'
      USING ERRCODE = '42501';
  END IF;

  RETURN QUERY
  WITH due AS (
    SELECT queue.id
    FROM public.seller_phone_sms_queue AS queue
    WHERE (
      queue.status = 'queued'
      AND queue.next_attempt_at <= pg_catalog.now()
    ) OR (
      queue.status = 'processing'
      AND queue.claimed_at < pg_catalog.now() - interval '5 minutes'
    )
    ORDER BY queue.created_at
    LIMIT pg_catalog.least(pg_catalog.greatest(p_batch_size, 1), 50)
    FOR UPDATE SKIP LOCKED
  ),
  claimed AS (
    UPDATE public.seller_phone_sms_queue AS queue
    SET status = 'processing',
        attempts = queue.attempts + 1,
        claimed_at = pg_catalog.now()
    FROM due
    WHERE queue.id = due.id
    RETURNING queue.id, queue.order_id
  )
  SELECT claimed.id, order_row.id, order_row.buyer_id, order_row.seller_id
  FROM claimed
  JOIN public.orders AS order_row ON order_row.id = claimed.order_id
  WHERE order_row.status = 'accepted';
END;
$$;

CREATE OR REPLACE FUNCTION public.finish_seller_phone_sms(
  p_queue_id bigint,
  p_success boolean,
  p_error text DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  current_attempts integer;
BEGIN
  IF COALESCE(auth.role(), '') <> 'service_role' THEN
    RAISE EXCEPTION 'Service role is required'
      USING ERRCODE = '42501';
  END IF;

  SELECT attempts INTO current_attempts
  FROM public.seller_phone_sms_queue
  WHERE id = p_queue_id
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'SMS queue item not found';
  END IF;

  IF p_success THEN
    UPDATE public.seller_phone_sms_queue
    SET status = 'sent',
        sent_at = pg_catalog.now(),
        claimed_at = NULL,
        last_error = NULL
    WHERE id = p_queue_id;
  ELSIF current_attempts >= 5 THEN
    UPDATE public.seller_phone_sms_queue
    SET status = 'failed',
        claimed_at = NULL,
        last_error = pg_catalog.left(COALESCE(p_error, 'Gateway delivery failed'), 300)
    WHERE id = p_queue_id;
  ELSE
    UPDATE public.seller_phone_sms_queue
    SET status = 'queued',
        next_attempt_at = pg_catalog.now()
          + pg_catalog.make_interval(
              mins => (2::numeric ^ current_attempts)::integer
            ),
        claimed_at = NULL,
        last_error = pg_catalog.left(COALESCE(p_error, 'Gateway delivery failed'), 300)
    WHERE id = p_queue_id;
  END IF;
END;
$$;

