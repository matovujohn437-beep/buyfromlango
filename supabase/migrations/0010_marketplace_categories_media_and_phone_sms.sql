CREATE OR REPLACE FUNCTION public.protect_order_updates()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  actor uuid := auth.uid();
BEGIN
  IF actor IS NULL OR public.is_admin() THEN
    RETURN NEW;
  END IF;

  IF NEW.listing_id IS DISTINCT FROM OLD.listing_id
     OR NEW.buyer_id IS DISTINCT FROM OLD.buyer_id
     OR NEW.seller_id IS DISTINCT FROM OLD.seller_id
     OR NEW.agreed_price_ugx IS DISTINCT FROM OLD.agreed_price_ugx
     OR NEW.agreed_quantity IS DISTINCT FROM OLD.agreed_quantity
     OR NEW.notes IS DISTINCT FROM OLD.notes
     OR NEW.phone_revealed_by_seller IS DISTINCT FROM OLD.phone_revealed_by_seller THEN
    RAISE EXCEPTION 'Order details can only be changed through negotiation actions'
      USING ERRCODE = '42501';
  END IF;

  IF actor = OLD.seller_id
     AND OLD.status = 'negotiating'
     AND NEW.status IN ('accepted', 'declined') THEN
    RETURN NEW;
  END IF;

  IF actor = OLD.buyer_id
     AND (
       (OLD.status = 'negotiating' AND NEW.status = 'cancelled')
       OR (OLD.status = 'accepted' AND NEW.status IN ('completed', 'cancelled'))
     ) THEN
    RETURN NEW;
  END IF;

  RAISE EXCEPTION 'This account cannot make that order status change'
    USING ERRCODE = '42501';
END;
$$;

CREATE TRIGGER protect_order_status_changes
  BEFORE UPDATE ON public.orders
  FOR EACH ROW
  EXECUTE FUNCTION public.protect_order_updates();

COMMIT;
