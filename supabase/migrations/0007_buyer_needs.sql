CREATE TABLE public.buyer_needs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  item_name text NOT NULL CHECK (length(btrim(item_name)) > 0),
  quantity numeric(14, 2) CHECK (quantity IS NULL OR quantity > 0),
  unit text,
  proposed_price_ugx numeric(14, 2)
    CHECK (proposed_price_ugx IS NULL OR proposed_price_ugx >= 0),
  notes text,
  contact_person text NOT NULL CHECK (length(btrim(contact_person)) > 0),
  contact_phone text NOT NULL CHECK (length(btrim(contact_phone)) > 0),
  district_id integer NOT NULL REFERENCES public.districts(id),
  subcounty_id integer REFERENCES public.subcounties(id) ON DELETE SET NULL,
  parish_id integer REFERENCES public.parishes(id) ON DELETE SET NULL,
  status text NOT NULL DEFAULT 'active'
    CHECK (status IN ('active', 'fulfilled', 'removed')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX buyer_needs_active_created_idx
  ON public.buyer_needs(status, created_at DESC);
CREATE INDEX buyer_needs_user_id_idx ON public.buyer_needs(user_id);

CREATE TRIGGER buyer_needs_set_updated_at
  BEFORE UPDATE ON public.buyer_needs
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

ALTER TABLE public.buyer_needs ENABLE ROW LEVEL SECURITY;

CREATE POLICY "users create their own buyer needs"
  ON public.buyer_needs FOR INSERT TO authenticated
  WITH CHECK (user_id = (SELECT auth.uid()));
CREATE POLICY "signed-in users read active buyer needs"
  ON public.buyer_needs FOR SELECT TO authenticated
  USING (status = 'active' OR user_id = (SELECT auth.uid()));
CREATE POLICY "users update their own buyer needs"
  ON public.buyer_needs FOR UPDATE TO authenticated
  USING (user_id = (SELECT auth.uid()))
  WITH CHECK (user_id = (SELECT auth.uid()));
CREATE POLICY "users delete their own buyer needs"
  ON public.buyer_needs FOR DELETE TO authenticated
  USING (user_id = (SELECT auth.uid()));
CREATE POLICY "admins manage buyer needs"
  ON public.buyer_needs FOR ALL TO authenticated
  USING ((SELECT public.is_admin()))
  WITH CHECK ((SELECT public.is_admin()));

REVOKE ALL ON public.buyer_needs FROM anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.buyer_needs TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.buyer_needs_id_seq TO authenticated;

CREATE VIEW public.public_buyer_needs AS
SELECT
  need.id,
  need.user_id,
  need.item_name,
  need.quantity,
  need.unit,
  need.proposed_price_ugx,
  need.notes,
  need.contact_person,
  need.district_id,
  district.name AS district_name,
  need.subcounty_id,
  subcounty.name AS subcounty_name,
  need.parish_id,
  parish.name AS parish_name,
  need.created_at
FROM public.buyer_needs AS need
JOIN public.districts AS district ON district.id = need.district_id
LEFT JOIN public.subcounties AS subcounty
  ON subcounty.id = need.subcounty_id
LEFT JOIN public.parishes AS parish ON parish.id = need.parish_id
WHERE need.status = 'active';

GRANT SELECT ON public.public_buyer_needs TO anon, authenticated;

ALTER TABLE public.chat_threads
  ALTER COLUMN listing_id DROP NOT NULL,
  ADD COLUMN buyer_need_id bigint
    REFERENCES public.buyer_needs(id) ON DELETE CASCADE,
  DROP CONSTRAINT IF EXISTS chat_threads_listing_id_buyer_id_key,
  ADD CONSTRAINT chat_threads_one_context
    CHECK ((listing_id IS NOT NULL) <> (buyer_need_id IS NOT NULL));

CREATE UNIQUE INDEX chat_threads_listing_buyer_uidx
  ON public.chat_threads(listing_id, buyer_id)
  WHERE listing_id IS NOT NULL;
CREATE UNIQUE INDEX chat_threads_need_buyer_uidx
  ON public.chat_threads(buyer_need_id, buyer_id)
  WHERE buyer_need_id IS NOT NULL;

CREATE POLICY "users contact active buyer needs"
  ON public.chat_threads FOR INSERT TO authenticated
  WITH CHECK (
    buyer_id = (SELECT auth.uid())
    AND buyer_id <> seller_id
    AND listing_id IS NULL
    AND EXISTS (
      SELECT 1
      FROM public.buyer_needs AS need
      WHERE need.id = chat_threads.buyer_need_id
        AND need.user_id = chat_threads.seller_id
        AND need.status = 'active'
    )
  );
