DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conrelid = 'public.listings'::regclass
      AND conname = 'listings_category_id_fkey'
  ) THEN
    ALTER TABLE public.listings
      ADD CONSTRAINT listings_category_id_fkey
      FOREIGN KEY (category_id) REFERENCES public.categories(id)
      ON DELETE RESTRICT;
  END IF;
END;
$$;

