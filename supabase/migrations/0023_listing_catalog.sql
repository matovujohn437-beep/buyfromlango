BEGIN;

DO $$
DECLARE
  catalog_id_type text;
  unit_id_type text;
BEGIN
  IF to_regclass('public.catalog_items') IS NOT NULL
     AND to_regclass('public.item_units') IS NOT NULL THEN
    SELECT data_type INTO catalog_id_type
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name = 'catalog_items'
      AND column_name = 'id';
    SELECT data_type INTO unit_id_type
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name = 'item_units'
      AND column_name = 'id';

    IF catalog_id_type = 'uuid' AND unit_id_type = 'uuid' THEN
      ALTER TABLE public.item_units
        ADD COLUMN legacy_uuid_id uuid,
        ADD COLUMN legacy_item_uuid uuid;
      UPDATE public.item_units
      SET legacy_uuid_id = id,
          legacy_item_uuid = item_id;

      ALTER TABLE public.catalog_items
        ADD COLUMN legacy_uuid_id uuid;
      UPDATE public.catalog_items
      SET legacy_uuid_id = id;

      ALTER TABLE public.item_units
        DROP CONSTRAINT item_units_item_id_fkey;
      ALTER TABLE public.catalog_items
        DROP CONSTRAINT catalog_items_pkey;
      ALTER TABLE public.catalog_items DROP COLUMN id;
      ALTER TABLE public.catalog_items
        ADD COLUMN id bigint GENERATED BY DEFAULT AS IDENTITY;
      ALTER TABLE public.catalog_items
        ADD CONSTRAINT catalog_items_pkey PRIMARY KEY (id);

      ALTER TABLE public.item_units
        ADD COLUMN item_id_rekeyed bigint;
      UPDATE public.item_units AS unit
      SET item_id_rekeyed = item.id
      FROM public.catalog_items AS item
      WHERE item.legacy_uuid_id = unit.legacy_item_uuid;

      IF EXISTS (
        SELECT 1
        FROM public.item_units
        WHERE item_id_rekeyed IS NULL
      ) THEN
        RAISE EXCEPTION
          'Some item units do not map to a catalog item';
      END IF;

      ALTER TABLE public.item_units
        DROP CONSTRAINT item_units_pkey;
      ALTER TABLE public.item_units DROP COLUMN id;
      ALTER TABLE public.item_units
        ADD COLUMN id bigint GENERATED BY DEFAULT AS IDENTITY;
      ALTER TABLE public.item_units
        ADD CONSTRAINT item_units_pkey PRIMARY KEY (id);
      ALTER TABLE public.item_units DROP COLUMN item_id;
      ALTER TABLE public.item_units
        RENAME COLUMN item_id_rekeyed TO item_id;
      ALTER TABLE public.item_units
        ALTER COLUMN item_id SET NOT NULL;
      ALTER TABLE public.item_units
        ADD CONSTRAINT item_units_item_id_fkey
        FOREIGN KEY (item_id) REFERENCES public.catalog_items(id)
        ON DELETE CASCADE;
    ELSIF catalog_id_type = 'uuid' OR unit_id_type = 'uuid' THEN
      RAISE EXCEPTION
        'Catalog and item unit IDs must both be UUIDs or both use repository IDs';
    END IF;
  END IF;
END;
$$;

CREATE TABLE IF NOT EXISTS public.catalog_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id text NOT NULL REFERENCES public.categories(id) ON DELETE CASCADE,
  name text NOT NULL CHECK (length(btrim(name)) > 0),
  sort_order integer NOT NULL DEFAULT 0,
  is_active boolean NOT NULL DEFAULT true,
  UNIQUE (category_id, name)
);

CREATE TABLE IF NOT EXISTS public.item_units (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id bigint NOT NULL REFERENCES public.catalog_items(id) ON DELETE CASCADE,
  unit_name text NOT NULL CHECK (length(btrim(unit_name)) > 0),
  sort_order integer NOT NULL DEFAULT 0,
  is_active boolean NOT NULL DEFAULT true,
  UNIQUE (item_id, unit_name)
);

ALTER TABLE public.catalog_items
  ADD COLUMN IF NOT EXISTS sort_order integer NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS is_active boolean NOT NULL DEFAULT true;
ALTER TABLE public.item_units
  ADD COLUMN IF NOT EXISTS sort_order integer NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS is_active boolean NOT NULL DEFAULT true;

ALTER TABLE public.catalog_items
  ALTER COLUMN category_id SET NOT NULL,
  ALTER COLUMN sort_order SET DEFAULT 0,
  ALTER COLUMN is_active SET DEFAULT true;
ALTER TABLE public.item_units
  ALTER COLUMN item_id SET NOT NULL,
  ALTER COLUMN sort_order SET DEFAULT 0,
  ALTER COLUMN is_active SET DEFAULT true;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conrelid = 'public.catalog_items'::regclass
      AND conname = 'catalog_items_category_name_key'
  ) THEN
    ALTER TABLE public.catalog_items
      ADD CONSTRAINT catalog_items_category_name_key
      UNIQUE (category_id, name);
  END IF;
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conrelid = 'public.item_units'::regclass
      AND conname = 'item_units_item_unit_name_key'
  ) THEN
    ALTER TABLE public.item_units
      ADD CONSTRAINT item_units_item_unit_name_key
      UNIQUE (item_id, unit_name);
  END IF;
END;
$$;

CREATE INDEX IF NOT EXISTS catalog_items_category_active_order_idx
  ON public.catalog_items (category_id, is_active, sort_order);
CREATE INDEX IF NOT EXISTS item_units_item_active_order_idx
  ON public.item_units (item_id, is_active, sort_order);

ALTER TABLE public.catalog_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.item_units ENABLE ROW LEVEL SECURITY;

CREATE POLICY "active catalog items are publicly readable"
  ON public.catalog_items FOR SELECT TO anon, authenticated
  USING (is_active);

CREATE POLICY "active item units are publicly readable"
  ON public.item_units FOR SELECT TO anon, authenticated
  USING (is_active);

GRANT SELECT ON public.catalog_items, public.item_units TO anon, authenticated;

