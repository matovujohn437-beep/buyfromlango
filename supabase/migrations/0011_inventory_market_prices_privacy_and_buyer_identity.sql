ALTER TABLE public.listings
  ADD COLUMN remaining_quantity numeric(14, 2)
    CHECK (remaining_quantity IS NULL OR remaining_quantity >= 0),
  ADD COLUMN sale_status text NOT NULL DEFAULT 'available'
    CHECK (sale_status IN ('available', 'partially_sold', 'sold'));

UPDATE public.listings
SET remaining_quantity = btrim(quantity)::numeric
WHERE quantity IS NOT NULL
  AND btrim(quantity) ~ '^[0-9]+([.][0-9]+)?$';

ALTER TABLE public.profiles
  ADD COLUMN account_type text NOT NULL DEFAULT 'individual'
    CHECK (account_type IN ('individual', 'cooperative')),
  ADD COLUMN item_visibility text NOT NULL DEFAULT 'public'
    CHECK (item_visibility IN ('public', 'contacts', 'private'));

DROP POLICY "active listings are publicly readable" ON public.listings;
CREATE OR REPLACE FUNCTION public.can_view_listing(owner_id uuid)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT owner_id = (SELECT auth.uid())
    OR (SELECT public.is_admin())
    OR EXISTS (
      SELECT 1
      FROM public.profiles AS profile
      WHERE profile.id = owner_id
        AND (
          profile.item_visibility = 'public'
          OR (
            profile.item_visibility = 'contacts'
            AND (SELECT auth.uid()) IS NOT NULL
            AND EXISTS (
              SELECT 1
              FROM public.chat_threads AS thread
              WHERE (thread.buyer_id = (SELECT auth.uid())
                  AND thread.seller_id = owner_id)
                 OR (thread.seller_id = (SELECT auth.uid())
                  AND thread.buyer_id = owner_id)
            )
          )
        )
    );
$$;
REVOKE ALL ON FUNCTION public.can_view_listing(uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.can_view_listing(uuid) TO anon, authenticated;

CREATE POLICY "visible listings are readable"
  ON public.listings FOR SELECT TO anon, authenticated
  USING (
    user_id = (SELECT auth.uid())
    OR (SELECT public.is_admin())
    OR (
      status = 'active'
      AND sale_status <> 'sold'
      AND public.can_view_listing(user_id)
    )
  );

DROP POLICY "media for visible listings is readable"
  ON public.listing_media;
CREATE POLICY "media for visible listings is readable"
  ON public.listing_media FOR SELECT TO anon, authenticated
  USING (
    EXISTS (
      SELECT 1
      FROM public.listings
      WHERE listings.id = listing_media.listing_id
        AND (
          listings.status = 'active'
          OR listings.user_id = (SELECT auth.uid())
          OR (SELECT public.is_admin())
        )
    )
  );

CREATE TABLE public.market_prices (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  district_id integer NOT NULL
    REFERENCES public.districts(id) ON DELETE CASCADE,
  item_name text NOT NULL CHECK (length(btrim(item_name)) > 0),
  wholesale_price_ugx numeric(14, 2) NOT NULL
    CHECK (wholesale_price_ugx >= 0),
  retail_price_ugx numeric(14, 2) NOT NULL
    CHECK (retail_price_ugx >= 0),
  price_change_percent numeric(8, 2) NOT NULL DEFAULT 0,
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (district_id, item_name)
);

ALTER TABLE public.market_prices ENABLE ROW LEVEL SECURITY;
CREATE POLICY "market prices are publicly readable"
  ON public.market_prices FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "admins manage market prices"
  ON public.market_prices FOR ALL TO authenticated
  USING ((SELECT public.is_admin()))
  WITH CHECK ((SELECT public.is_admin()));

GRANT SELECT ON public.market_prices TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON public.market_prices TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.market_prices_id_seq TO authenticated;

CREATE OR REPLACE VIEW public.public_buyer_needs AS
SELECT
  need.id,
  need.user_id,
  need.item_name,
  need.quantity,
  need.unit,
  need.proposed_price_ugx,
  need.notes,
  need.contact_person,
  need.district_id,
  district.name AS district_name,
  need.subcounty_id,
  subcounty.name AS subcounty_name,
  need.parish_id,
  parish.name AS parish_name,
  need.created_at,
  CASE
    WHEN profile.is_anonymous THEN 'Anonymous buyer'
    ELSE COALESCE(NULLIF(profile.full_name, ''), 'Buyer')
  END AS poster_name,
  CASE WHEN profile.is_anonymous THEN NULL ELSE profile.avatar_url END
    AS poster_avatar_url,
  profile.is_verified AS poster_is_verified,
  profile.account_type AS poster_account_type
FROM public.buyer_needs AS need
JOIN public.districts AS district ON district.id = need.district_id
LEFT JOIN public.subcounties AS subcounty
  ON subcounty.id = need.subcounty_id
LEFT JOIN public.parishes AS parish ON parish.id = need.parish_id
JOIN public.profiles AS profile ON profile.id = need.user_id
WHERE need.status = 'active';

GRANT SELECT ON public.public_buyer_needs TO anon, authenticated;
